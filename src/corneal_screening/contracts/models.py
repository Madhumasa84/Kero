class AnalysisResult(ContractModel):
    schema_version: str = Field(default="1.0.0", min_length=1, max_length=32)
    software_version: str = Field(min_length=1, max_length=64)
    analysis_id: UUID
    analysis_mode: AnalysisMode
    timestamp: datetime = Field(json_schema_extra=_AWARE_DATETIME_JSON_SCHEMA)
    anonymous_patient_id: str = Field(min_length=1, max_length=128)
    eye: Eye
    capture_session_id: str = Field(min_length=1, max_length=128)
    operator_id: str = Field(min_length=1, max_length=128)
    capture_timestamp: datetime = Field(json_schema_extra=_AWARE_DATETIME_JSON_SCHEMA)
    status: ResultStatus
    reason_codes: list[ReasonCode] = Field(min_length=1)
    message: str = Field(min_length=1)
    stage_execution: list[StageExecution] = Field(min_length=1)
    device_version: str = Field(min_length=1, max_length=128)
    device_configuration_hash: str | None = Field(
        default=None, pattern=r"^[0-9a-f]{64}$"
    )
    calibration_status: CalibrationStatus
    calibration_identifier: str | None = None
    original_image_sha256: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    quality_measurements: QualityMeasurements
    centre_information: CentreInformation
    ring_tracking: RingTrackingInformation
    features: FeatureMeasurements
    artifact_references: list[ArtifactReference] = Field(default_factory=list)
    screening_disclaimer: str = SCREENING_DISCLAIMER

    _timestamp_timezone = field_validator("timestamp")(_require_timezone)
    _capture_timestamp_timezone = field_validator("capture_timestamp")(
        _require_timezone
    )

    def to_json(self) -> str:
        """Serialize using strict JSON rules; unavailable numbers remain null."""

        return json.dumps(
            self.model_dump(mode="json"),
            ensure_ascii=False,
            allow_nan=False,
            separators=(",", ":"),
        )


