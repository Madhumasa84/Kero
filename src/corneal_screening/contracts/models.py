class RuntimeLimits(ContractModel):
    """Limits applied before an image is decoded or processed."""

    max_upload_bytes: int = Field(gt=0)
    max_decoded_width_px: int = Field(gt=0)
    max_decoded_height_px: int = Field(gt=0)
    max_decoded_pixels: int = Field(gt=0)
    supported_extensions: list[str] = Field(min_length=1)

    @field_validator("supported_extensions")
    @classmethod
    def _normalise_extensions(cls, value: list[str]) -> list[str]:
        normalised = [extension.strip().lower() for extension in value]
        if any(not extension.startswith(".") for extension in normalised):
            raise ValueError("supported extensions must start with '.'")
        if len(set(normalised)) != len(normalised):
            raise ValueError("supported extensions must be unique")
        return normalised


